"""Builds the letter-trigram tables for autoswitch: assets/ngrams/<lang>.tsv.

Standard library only. Input: public-domain texts you downloaded yourself
(plain text or HTML); they are not part of the repository, only the counts
are. Usage:

    python tools/make_ngrams.py en pg1342.txt pg11.txt
    python tools/make_ngrams.py ru ru_*.html
    python tools/make_ngrams.py uk uk_khmary.html

Scoring must match `retype-core/src/ngram.rs`: a word is padded as
"^word$", and its score is the mean over its trigrams of
ln((count + 0.5) / total), with count 0 for trigrams not in the table.
"""

import html
import math
import re
import sys
from collections import Counter
from pathlib import Path

ALPHABETS = {
    "en": "abcdefghijklmnopqrstuvwxyz'",
    "ru": "абвгдежзийклмнопрстуфхцчшщъыьэюя",
    "uk": "абвгґдеєжзиіїйклмнопрстуфхцчшщьюя'",
}
# Spelling variants folded before counting (the core folds them too).
FOLD = {"ё": "е", "’": "'", "ʼ": "'"}
TOP = 8000
ROOT = Path(__file__).resolve().parent.parent


def text_of(path):
    raw = path.read_text(encoding="utf-8", errors="replace")
    start = raw.find("*** START OF")
    end = raw.find("*** END OF")
    if start != -1 and end != -1:  # Project Gutenberg header and licence
        raw = raw[raw.index("\n", start) : end]
    if path.suffix.lower() in (".html", ".htm"):
        raw = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", raw)
        raw = re.sub(r"<[^>]+>", " ", raw)
        raw = html.unescape(raw)
    return raw


def words(text, alphabet):
    text = "".join(FOLD.get(c, c) for c in text.lower())
    pattern = "[" + re.escape(alphabet) + "]+"
    for word in re.findall(pattern, text):
        word = word.strip("'")
        if len(word) >= 2:
            yield word


def trigrams(word):
    padded = "^" + word + "$"
    return [padded[i : i + 3] for i in range(len(padded) - 2)]


def score(word, table, total):
    grams = trigrams(word)
    return sum(math.log((table.get(g, 0) + 0.5) / total) for g in grams) / len(grams)


def main():
    lang, files = sys.argv[1], [Path(p) for p in sys.argv[2:]]
    alphabet = ALPHABETS[lang]
    counts = Counter()
    corpus_words = []
    for path in files:
        for word in words(text_of(path), alphabet):
            corpus_words.append(word)
            counts.update(trigrams(word))
    total = sum(counts.values())
    table = dict(counts.most_common(TOP))
    # Mean word score over the corpus with the truncated table: the
    # language's "normal" level, so languages can be compared.
    baseline = sum(score(w, table, total) for w in corpus_words) / len(corpus_words)
    out = ROOT / "assets" / "ngrams" / f"{lang}.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# retype letter-trigram table, generated by tools/make_ngrams.py\n")
        f.write(f"# words {len(corpus_words)}\n")
        f.write(f"total\t{total}\n")
        f.write(f"baseline\t{baseline:.4f}\n")
        for gram, count in sorted(table.items(), key=lambda kv: (-kv[1], kv[0])):
            f.write(f"{gram}\t{count}\n")
    print(f"{lang}: {len(corpus_words)} words, {len(counts)} trigrams, kept {len(table)}, "
          f"baseline {baseline:.3f} -> {out}")


if __name__ == "__main__":
    main()
